export const catalogues: Record<Locale, Record<Key, string>> = { 'en-IN': en, 'hi-IN': hi }

export function translate(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  const text = (catalogues[locale] as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ''))
}

export const LocaleContext = createContext<{ locale: Locale; setLocale: (l: Locale) => void }>({ locale: 'en-IN', setLocale: () => {} })

export function useT() {
  const { locale } = useContext(LocaleContext)
  return (key: string, vars?: Record<string, string | number>) => translate(locale, key, vars)
}
